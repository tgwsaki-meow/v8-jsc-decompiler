#!/usr/bin/env node
// tools/profilegen/diff.mjs
//
// Diff two generated profiles and write a markdown report.
//
//   node tools/profilegen/diff.mjs 14.4.258.16 14.6.202.34 --out profiles/DIFF-14.4-vs-14.6.md

import fs from 'node:fs';
import path from 'node:path';
import { loadProfile } from '../../src/profile/index.mjs';

const args = process.argv.slice(2);
const tags = args.filter((a) => /^\d+\.\d+\.\d+\.\d+$/.test(a));
let out = null;
let root = 'profiles';
for (let i = 0; i < args.length; i++) {
  if (args[i] === '--out') out = args[++i];
  else if (args[i] === '--profiles') root = args[++i];
}
if (tags.length !== 2) {
  console.error('usage: node tools/profilegen/diff.mjs <tagA> <tagB> [--out file.md] [--profiles profiles]');
  process.exitCode = 2;
} else {
  const a = loadProfile(path.join(root, tags[0]), { strict: false });
  const b = loadProfile(path.join(root, tags[1]), { strict: false });
  const md = render(a, b);
  if (out) { fs.mkdirSync(path.dirname(out), { recursive: true }); fs.writeFileSync(out, md, 'utf8'); console.log(`wrote ${out}`); }
  else console.log(md);
}

function render(a, b) {
  const L = [];
  const say = (s = '') => L.push(s);

  say(`# V8 profile diff: ${a.version} -> ${b.version}`);
  say();
  say(`Generated by \`tools/profilegen/diff.mjs\` from \`profiles/${a.version}/\` and \`profiles/${b.version}/\`.`);
  say(`Both profiles are variant \`${a.variant}\` at \`kTaggedSize = ${a.taggedSize}\`.`);
  say();

  // ------------------------------------------------------------- headline
  say('## Summary');
  say();
  say('| table | ' + a.version + ' | ' + b.version + ' | delta |');
  say('|---|---:|---:|---|');
  const rows = [
    ['opcodes', a.opcodeCount, b.opcodeCount],
    ['operand types', a.tables.operands.operandTypeOrder.length, b.tables.operands.operandTypeOrder.length],
    ['serializer tags', a.tables.serializerTags.count, b.tables.serializerTags.count],
    ['roots (total)', a.rootCount, b.rootCount],
    ['roots (read-only)', a.readOnlyRootCount, b.readOnlyRootCount],
    ['static-roots entries', a.tables.staticRoots.entriesCount, b.tables.staticRoots.entriesCount],
    ['Torque map roots', a.tables.roots.torqueDefinedMapRootCount, b.tables.roots.torqueDefinedMapRootCount],
    ['runtime function ids', a.tables.runtime.count, b.tables.runtime.count],
    ['intrinsics', a.tables.intrinsics.count, b.tables.intrinsics.count],
    ['bitfield structs', Object.keys(a.tables.layouts.bitfields).length, Object.keys(b.tables.layouts.bitfields).length],
  ];
  for (const [name, x, y] of rows) {
    const d = y - x;
    say(`| ${name} | ${x} | ${y} | ${d === 0 ? 'same' : (d > 0 ? '+' : '') + d} |`);
  }
  say();

  // ------------------------------------------------------------- opcodes
  say('## Opcodes');
  say();
  const renumbered = [];
  const onlyA = [];
  const onlyB = [];
  const sigChanged = [];
  for (const [name, v] of Object.entries(a.tables.bytecodes.byName)) {
    const w = b.tables.bytecodes.byName[name];
    if (w === undefined) { onlyA.push(name); continue; }
    if (w !== v) renumbered.push([name, v, w]);
    const oa = a.getOpcode(v); const ob = b.getOpcode(w);
    if (oa.operands.join(',') !== ob.operands.join(',') || oa.implicitRegisterUse !== ob.implicitRegisterUse) {
      sigChanged.push([name, oa, ob]);
    }
  }
  for (const name of Object.keys(b.tables.bytecodes.byName)) {
    if (a.tables.bytecodes.byName[name] === undefined) onlyB.push(name);
  }
  say(`* opcode count: **${a.opcodeCount} -> ${b.opcodeCount}**`);
  say(`* removed: ${onlyA.length ? onlyA.join(', ') : '**none**'}`);
  say(`* added: ${onlyB.length ? onlyB.join(', ') : '**none**'}`);
  say(`* renumbered: ${renumbered.length ? renumbered.map(([n, x, y]) => `${n} 0x${x.toString(16)}->0x${y.toString(16)}`).join(', ') : '**none** -- the numbering is byte-identical'}`);
  say(`* signature changes: **${sigChanged.length}**`);
  say();
  if (sigChanged.length) {
    say('| opcode | value | ' + a.version + ' | ' + b.version + ' | encoded length at scale 1 / 2 / 4 |');
    say('|---|---|---|---|---|');
    for (const [name, oa, ob] of sigChanged) {
      const la = [1, 2, 4].map((s) => a.instructionLength(name, s)).join('/');
      const lb = [1, 2, 4].map((s) => b.instructionLength(name, s)).join('/');
      say(`| \`${name}\` | 0x${oa.value.toString(16)} | \`[${oa.operands.join(', ')}]\` | \`[${ob.operands.join(', ')}]\` | ${la} -> ${lb} |`);
    }
    say();
  }

  // operand type churn
  const opA = new Set(a.tables.operands.operandTypeOrder);
  const opB = new Set(b.tables.operands.operandTypeOrder);
  const opAdded = [...opB].filter((x) => !opA.has(x));
  const opRemoved = [...opA].filter((x) => !opB.has(x));
  say('### Operand types');
  say();
  say(`* added: ${opAdded.length ? opAdded.map((x) => `\`${x}\``).join(', ') : 'none'}`);
  say(`* removed: ${opRemoved.length ? opRemoved.map((x) => `\`${x}\``).join(', ') : 'none'}`);
  say();
  for (const t of opAdded) {
    const d = b.operandType(t);
    say(`\`${t}\`: ${d.typeInfo}, baseSize ${d.baseSize}, ${d.scalable ? 'scalable' : 'fixed width'}, ${d.signed ? 'signed' : 'unsigned'}`);
  }
  for (const t of ['kFeedbackSlot']) {
    if (!opA.has(t)) continue;
    const d = a.operandType(t);
    say(`\`${t}\` (${a.version}): ${d.typeInfo}, baseSize ${d.baseSize}, ${d.scalable ? 'scalable' : 'fixed width'}`);
  }
  say();
  say('**Why this matters for a decoder.** A scalable operand grows with the'
    + ' `Wide`/`ExtraWide` prefix; a fixed one does not. Any opcode that moved from'
    + ' a scalable to a fixed operand changes its encoded length under a prefix, so'
    + ' decoding one version with the other version\'s table desynchronises the'
    + ' instruction stream from that point on.');
  say();

  // ------------------------------------------------------------- roots
  say('## Roots');
  say();
  const ra = Object.values(a.tables.roots.byIndex);
  const rb = Object.values(b.tables.roots.byIndex);
  const sa = new Set(ra.map((r) => r.cppName));
  const sb = new Set(rb.map((r) => r.cppName));
  const added = rb.filter((r) => !sa.has(r.cppName));
  const removed = ra.filter((r) => !sb.has(r.cppName));
  let first = null;
  for (let i = 0; i < Math.min(ra.length, rb.length); i++) {
    if (ra[i].cppName !== rb[i].cppName) { first = i; break; }
  }
  say(`* total roots: **${ra.length} -> ${rb.length}**; read-only **${a.readOnlyRootCount} -> ${b.readOnlyRootCount}**`);
  say(`* removed: ${removed.length ? removed.map((r) => `\`${r.cppName}\``).join(', ') : '**none**'}`);
  say(`* added (${added.length}):`);
  say();
  if (added.length) {
    say('| index in ' + b.version + ' | name | kind |');
    say('|---:|---|---|');
    for (const r of added) say(`| ${r.index} | \`${r.cppName}\` | ${r.kind} |`);
    say();
  }
  say(`* **first index where the root order diverges: ${first}** (\`${ra[first]?.cppName}\` vs \`${rb[first]?.cppName}\`)`);
  say();
  const intl = a.tables.roots.intlOnlyRootCount;
  const prune = (p) => Object.values(p.tables.roots.byIndex)
    .filter((r) => !r.intlOnly && r.cppName !== 'close_parenthesis_string')
    .map((r) => r.cppName);
  const pa = prune(a); const pb = prune(b);
  let pruned = null;
  for (let i = 0; i < Math.min(pa.length, pb.length); i++) if (pa[i] !== pb[i]) { pruned = i; break; }
  say('### Note on the index: 504 vs ' + first);
  say();
  say(`\`scratch/recon/VERSION_PLUGGABILITY.md\` §3.4 reported this divergence at index **504**.`);
  say(`That figure was measured against a root expansion that silently dropped the`);
  say(`**${intl}** \`V8_INTL_SUPPORT\` internalized strings (it kept the empty \`#else\` body of the`);
  say(`doubly-defined \`INTERNALIZED_STRING_LIST_GENERATOR_INTL\`) and also lost`);
  say('`close_parenthesis_string` to a paren matcher that counted the `)` inside the');
  say('string literal `")"`. The divergence is the *same pair of roots*; only the index moved:');
  say();
  say('```');
  say(`corrected first divergence            ${first}`);
  say(`minus ${intl} V8_INTL_SUPPORT strings      -${intl}`);
  say('minus close_parenthesis_string         -1');
  say(`                                     = ${pruned}   <- the previously reported figure`);
  say('```');
  say();
  say(`Verified by pruning exactly those roots from both corrected lists, which puts the`);
  say(`first divergence back at **${pruned}**. The ${first} figure is the correct one for the real`);
  say(`\`${a.variant}\` build: it agrees positionally with \`StaticReadOnlyRootsPointerTable\``);
  say(`at ${a.acceptance.roots.agreement} (${a.version}) and ${b.acceptance.roots.agreement} (${b.version}).`);
  say();
  say('**Consequence.** Root indices are not portable across these two tags. A');
  say(`serialized \`kRootArray\` reference with index >= ${first} names a different root in`);
  say('each version.');
  say();

  // static root addresses
  say('### Static-root addresses');
  say();
  const addrA = a.tables.staticRoots;
  const addrB = b.tables.staticRoots;
  let sameAddr = 0; let movedAddr = 0;
  const byNameA = new Map(addrA.orderedTable.map((e) => [e.camelName, e.address]));
  for (const e of addrB.orderedTable) {
    if (!byNameA.has(e.camelName)) continue;
    if (byNameA.get(e.camelName) === e.address) sameAddr++; else movedAddr++;
  }
  say(`* table length: ${addrA.entriesCount} -> ${addrB.entriesCount} (header \`${addrA.header}\` in both)`);
  say(`* roots present in both: ${sameAddr + movedAddr}; same compressed address ${sameAddr}, moved ${movedAddr}`);
  const minA = Math.min(...addrA.orderedTable.map((e) => e.address));
  const maxA = Math.max(...addrA.orderedTable.map((e) => e.address));
  const minB = Math.min(...addrB.orderedTable.map((e) => e.address));
  const maxB = Math.max(...addrB.orderedTable.map((e) => e.address));
  say(`* address range: 0x${minA.toString(16)}..0x${maxA.toString(16)} -> 0x${minB.toString(16)}..0x${maxB.toString(16)}`);
  say();

  // ------------------------------------------------------------- the rest
  say('## Serializer tags');
  say();
  const ta = a.tables.serializerTags.tags;
  const tb = b.tables.serializerTags.tags;
  const tagDiff = Object.keys({ ...ta, ...tb }).filter((k) => ta[k] !== tb[k]);
  say(`${Object.keys(ta).length} tags in both; ${tagDiff.length ? 'changed: ' + tagDiff.join(', ') : '**no change at all** (values, names and the ranged-tag spans are identical)'}.`);
  say(`\`kNumberOfSnapshotSpaces\` = ${a.tables.serializerTags.kNumberOfSnapshotSpaces} in both, so \`kNewObject\` occupies 0x00..0x0${a.tables.serializerTags.rangedTags.kNewObject.end}.`);
  say();

  say('## Runtime functions and intrinsics');
  say();
  const fnA = new Set(Object.values(a.tables.runtime.byId).map((e) => e.name));
  const fnB = new Set(Object.values(b.tables.runtime.byId).map((e) => e.name));
  const fnAdded = [...fnB].filter((x) => !fnA.has(x));
  const fnRemoved = [...fnA].filter((x) => !fnB.has(x));
  let fnFirst = null;
  for (let i = 0; i < Math.min(a.tables.runtime.count, b.tables.runtime.count); i++) {
    if (a.runtimeName(i) !== b.runtimeName(i)) { fnFirst = i; break; }
  }
  say(`* runtime ids: ${a.tables.runtime.count} -> ${b.tables.runtime.count}`);
  say(`* added: ${fnAdded.length ? fnAdded.map((x) => `\`${x}\``).join(', ') : 'none'}`);
  say(`* removed: ${fnRemoved.length ? fnRemoved.map((x) => `\`${x}\``).join(', ') : 'none'}`);
  say(`* first id whose name differs: ${fnFirst === null ? 'none' : `**${fnFirst}** (\`${a.runtimeName(fnFirst)}\` vs \`${b.runtimeName(fnFirst)}\`)`}`);
  say(`* intrinsics: ${a.tables.intrinsics.count} -> ${b.tables.intrinsics.count}; `
    + `${JSON.stringify(Object.values(a.tables.intrinsics.byId).map((e) => e.name)) === JSON.stringify(Object.values(b.tables.intrinsics.byId).map((e) => e.name)) ? 'identical list and ordering' : 'list differs'}`);
  say();
  say(`\`CallRuntime\`\'s operand is a runtime function id, so a shifted id renames the call.`);
  say();

  say('## Object layouts');
  say();
  const classNames = [...new Set([...Object.keys(a.tables.layouts.classes), ...Object.keys(b.tables.layouts.classes)])].sort();
  const layoutChanges = [];
  for (const n of classNames) {
    const ca = a.tables.layouts.classes[n];
    const cb = b.tables.layouts.classes[n];
    if (!ca || !cb) { layoutChanges.push([n, ca ? 'present' : 'absent', cb ? 'present' : 'absent']); continue; }
    const fa = (ca.fields ?? []).map((f) => `${f.name}@${f.relativeOffset}/${f.size}`).join(' ');
    const fb = (cb.fields ?? []).map((f) => `${f.name}@${f.relativeOffset}/${f.size}`).join(' ');
    if (fa !== fb || ca.headerSize !== cb.headerSize || ca.parentSize !== cb.parentSize) {
      // name the fields that actually differ, not just the counts
      const la = ca.fields ?? []; const lb = cb.fields ?? [];
      const detail = [];
      if (ca.headerSize !== cb.headerSize) detail.push(`headerSize ${ca.headerSize} -> ${cb.headerSize}`);
      for (let i = 0; i < Math.max(la.length, lb.length); i++) {
        const x = la[i]; const y = lb[i];
        const sx = x ? `${x.name}@+${x.relativeOffset}/${x.size}` : '(absent)';
        const sy = y ? `${y.name}@+${y.relativeOffset}/${y.size}` : '(absent)';
        if (sx !== sy) detail.push(`slot ${i}: \`${sx}\` -> \`${sy}\``);
      }
      layoutChanges.push([n, `header ${ca.headerSize}, ${la.length} fields`, `header ${cb.headerSize}, ${lb.length} fields`, detail.join('; ')]);
    }
  }
  if (!layoutChanges.length) {
    say(`All ${classNames.length} profiled classes have identical field programs, header sizes and parent sizes.`);
  } else {
    say(`${classNames.length} classes profiled; ${layoutChanges.length} differ.`);
    say();
    say('| class | ' + a.version + ' | ' + b.version + ' | what changed |');
    say('|---|---|---|---|');
    for (const [n, x, y, d] of layoutChanges) say(`| \`${n}\` | ${x} | ${y} | ${d ?? ''} |`);
  }
  say();
  const bfChanges = [];
  for (const n of new Set([...Object.keys(a.tables.layouts.bitfields), ...Object.keys(b.tables.layouts.bitfields)])) {
    const x = a.tables.layouts.bitfields[n];
    const y = b.tables.layouts.bitfields[n];
    if (!x || !y) { bfChanges.push([n, x ? 'present' : 'absent', y ? 'present' : 'absent']); continue; }
    const fx = x.fields.map((f) => `${f.name}@${f.offset}+${f.width}`).join(' ');
    const fy = y.fields.map((f) => `${f.name}@${f.offset}+${f.width}`).join(' ');
    if (fx !== fy) bfChanges.push([n, `${x.fields.length} fields / ${x.usedBits} bits`, `${y.fields.length} fields / ${y.usedBits} bits`]);
  }
  say('### Bitfield structs');
  say();
  if (!bfChanges.length) say('No change in any bitfield struct.');
  else {
    say('| struct | ' + a.version + ' | ' + b.version + ' |');
    say('|---|---|---|');
    for (const [n, x, y] of bfChanges) say(`| \`${n}\` | ${x} | ${y} |`);
  }
  say();

  say('## Constants');
  say();
  const constChanges = [];
  const walk = (x, y, prefix) => {
    for (const k of new Set([...Object.keys(x ?? {}), ...Object.keys(y ?? {})])) {
      const vx = x?.[k]; const vy = y?.[k];
      if (vx && typeof vx === 'object' && !Array.isArray(vx)) { walk(vx, vy, `${prefix}${k}.`); continue; }
      if (JSON.stringify(vx) !== JSON.stringify(vy)) constChanges.push([`${prefix}${k}`, vx, vy]);
    }
  };
  for (const section of ['sizes', 'tagging', 'scopeInfo', 'handlerTable', 'sourcePositionTable', 'codeCacheHeader']) {
    walk(a.constants[section], b.constants[section], `${section}.`);
  }
  walk(a.constants.readOnlyPage, b.constants.readOnlyPage, 'readOnlyPage.');
  if (!constChanges.length) say('Every constant in `constants.json` (sizes, tagging, RO page geometry, handler table, source-position table, `.jsc` header) is identical.');
  else {
    say('| constant | ' + a.version + ' | ' + b.version + ' |');
    say('|---|---|---|');
    for (const [k, x, y] of constChanges) say(`| \`${k}\` | ${JSON.stringify(x)} | ${JSON.stringify(y)} |`);
  }
  say();

  say('## What a decoder must do differently');
  say();
  say('1. Use the per-tag `operands.json`: the six compare bytecodes change operand');
  say('   width, so instruction lengths differ under `Wide`/`ExtraWide`.');
  say(`2. Use the per-tag \`roots.json\`: indices from ${first} up name different roots.`);
  say('3. Use the per-tag `static-roots.json`: compressed read-only addresses move.');
  say('4. `serializer-tags.json`, `intrinsics.json`, `layouts.json` and `constants.json`');
  say('   happen to be interchangeable between these two tags, but nothing guarantees');
  say('   that for the next pair, so they stay per-tag too.');
  say();

  say('## Unresolved in either profile');
  say();
  for (const p of [a, b]) {
    const keys = Object.keys(p.unresolved);
    say(`**${p.version}**: ${keys.length ? keys.join(', ') : 'nothing'}`);
    for (const k of keys) {
      const v = p.unresolved[k];
      const note = v && typeof v === 'object' && !Array.isArray(v) ? (v.note ?? JSON.stringify(v)) : JSON.stringify(v);
      say(`* \`${k}\`: ${String(note).slice(0, 400)}`);
    }
    say();
  }

  return L.join('\n') + '\n';
}
