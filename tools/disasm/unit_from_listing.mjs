// tools/disasm/unit_from_listing.mjs
//
// Build a FunctionUnit (ARCHITECTURE.md 8.1) out of a parsed
// `--print-bytecode` listing, so the decoder can be exercised against an
// engine for which no matching code cache is obtainable.
//
// WHY THIS IS NEEDED, AND EXACTLY HOW CIRCULAR IT IS
// ---------------------------------------------------------------------------
// Both generated profiles describe a SANDBOXED V8 build
// (layouts.json: ExposedTrustedObject carries `self_indirect_pointer`), which
// is what Chromium and Electron ship -- and what this project's corpus is. The
// node binary on this machine is V8 14.6.202.34 but is built WITHOUT the
// sandbox, so its code cache has no kIndirectPointerPrefix /
// kInitializeSelfIndirectPointer tags and its trusted objects have no
// self-pointer slot. A 14.6 .jsc from node therefore cannot be read with the
// 14.6 profile, and there is no sandboxed 14.6 engine here to produce one.
//
// So for 14.6 the input side of the test comes from the listing instead:
//
//   taken from V8, as DATA (not a decoding):
//     * the bytecode bytes, from the hex column V8 prints per instruction;
//     * parameter count / register count / frame size, from the header lines;
//     * the constant pool, from V8's own pool dump (node dumps it; a release
//       d8 does not, which is why this mode is only used with node).
//
//   therefore NOT tested in this mode (tested in cache mode on 14.4 instead):
//     * reading the bytecode, constant pool and handler table out of a
//       serialized BytecodeArray;
//     * decoding the source position table -- the unit is given none and the
//       comparison skips source positions.
//
//   still tested in this mode, which is the point:
//     * instruction boundaries and encoded lengths at every scale, i.e. the
//       per-version operand table (the six comparison bytecodes that moved
//       from a scalable kFeedbackSlot to a fixed kEmbeddedFeedback in 14.6);
//     * every operand's decoding and rendering, including registers;
//     * jump arithmetic (opcodeByteOffset +/- delta, constant-pool deltas);
//     * jump tables (span, case numbering, target arithmetic).

import { stripAddress } from '../../src/verify/bytecode_parser.mjs';

/**
 * Per-function constant pools, read straight out of the raw listing.
 *
 * src/verify/bytecode_parser.mjs reads pool rows with /^\s*(\d+):/, which
 * misses the RANGE form FixedArray::PrintElements emits when consecutive slots
 * hold the same value:
 *
 *       3-4: 28
 *
 * That form is exactly what a switch with a fall-through case produces (two
 * jump-table slots with the same relative target), so without it the jump
 * table comes out short. The parser is shared, already self-tested and
 * compares V8 to V8 where this does not matter, so it is left alone and the
 * range form is handled here, where the pool is actually consumed.
 */
export function poolsFromRawListing(text) {
  const out = [];
  let cur = null, inPool = false;
  for (const line of text.split(/\r?\n/)) {
    const t = line.trim();
    if (/^\[generated bytecode for function:/.test(t)) { cur = new Map(); out.push(cur); inPool = false; continue; }
    if (!cur) continue;
    if (/^Constant pool \(size = \d+\)$/.test(t)) { inPool = true; continue; }
    if (/^(Handler Table|Source Position Table)\s*\(size/.test(t)) { inPool = false; continue; }
    if (!inPool) continue;
    let m;
    if ((m = /^\s*(\d+)\s*-\s*(\d+):\s*([\s\S]*?)\s*$/.exec(line))) {
      for (let i = +m[1]; i <= +m[2]; i++) cur.set(i, m[3]);
      continue;
    }
    if ((m = /^\s*(\d+):\s*([\s\S]*?)\s*$/.exec(line))) { cur.set(+m[1], m[2]); continue; }
  }
  return out;
}

/** `0x... <String[1]: #d>` and friends -> an 8.1 constant. */
function constantFromListing(entry) {
  if (entry === undefined || entry === null) {
    return { t: 'unresolved', why: 'poolNotDumped', detail: 'the engine did not dump this constant pool slot' };
  }
  const v = stripAddress(String(typeof entry === 'string' ? entry : (entry.value ?? '')).trim());
  if (/^-?\d+$/.test(v)) return { t: 'number', v: Number(v) };
  const str = /^<String\[\d+\]:\s*#?([\s\S]*)>$/.exec(v);
  if (str) return { t: 'string', v: str[1] };
  const num = /^<HeapNumber\s+([-\d.eE+]+)>$/.exec(v);
  if (num) return { t: 'number', v: Number(num[1]) };
  return { t: 'unresolved', why: 'listingOnly', detail: v };
}

/**
 * @param {object} fn one entry of parseBytecodeDump().functions
 * @param {{profile: object, pool?: Map<number,string>}} opts
 * @returns {object} a FunctionUnit
 */
export function unitFromListing(fn, opts) {
  const sys = opts.profile.constants.sizes.kSystemPointerSize;
  const bytes = [];
  for (const ins of fn.instructions) for (const b of ins.bytes) bytes.push(b);
  const bytecode = Buffer.from(bytes);
  const constants = [];
  const n = fn.constantPoolSize ?? fn.constantPool.length;
  for (let i = 0; i < n; i++) {
    const fromRaw = opts.pool?.get(i);
    constants.push(constantFromListing(fromRaw !== undefined ? fromRaw : fn.constantPool[i]));
  }
  return {
    sfiId: null,
    bytecodeId: null,
    functionLiteralId: null,
    name: fn.name || '',
    kind: null,
    isGenerator: false,
    isAsync: false,
    isStrict: null,
    startPosition: null,
    endPosition: null,

    bytecode,
    frameSize: fn.frameSize ?? (fn.registerCount ?? 0) * sys,
    parameterCount: fn.parameterCount,
    maxArguments: null,
    registerCount: fn.registerCount,
    incomingNewTargetOrGeneratorRegister: 0,

    constants,
    handlers: fn.handlerTable.map((h) => ({
      rangeStart: h.from, rangeEnd: h.to, handlerOffset: h.handler,
      prediction: h.prediction, wasUsed: null, data: h.data,
    })),
    handlerTableSize: fn.handlerTableSize,
    // deliberately empty: see the header comment
    sourcePositions: [],
    sourcePositionTableSize: fn.sourcePositionTableSize,
    scope: null,
    uncompiled: null,
    warnings: [{ code: 'listingDerived', detail: 'FunctionUnit reconstructed from a --print-bytecode listing; no source positions' }],
    _source: 'unit_from_listing',
  };
}

export default { unitFromListing };
